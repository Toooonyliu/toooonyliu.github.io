import { chromium } from "playwright";
import assert from "node:assert/strict";
const browser = await chromium.launch({headless:true,executablePath:"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"});
const page = await browser.newPage({viewport:{width:1280,height:1000},deviceScaleFactor:1});
const errors=[];
const qaPrefix=process.env.QA_PREFIX||"iteration4";
page.on("pageerror",error=>errors.push(error.message));
const snap=async name=>{await page.mouse.move(20,20);await page.waitForTimeout(450);assert.deepEqual(await page.locator(".device-screen img").evaluateAll(images=>images.filter(image=>!image.complete||image.naturalWidth===0).map(image=>image.src)),[],`${name}: images must load`);await page.screenshot({path:`qa/${qaPrefix}-${name}.png`});};
try {
  await page.goto("http://127.0.0.1:4173/",{waitUntil:"networkidle"});
  assert.equal(await page.locator(".social-app.is-map").count(),1,"Home must open on the map");
  await snap("home");
  assert.equal(await page.locator(".world-pin").count(),5);
  await page.getByRole("button",{name:"Zoom in",exact:true}).click();
  assert.equal(await page.locator(".map-world").getAttribute("data-zoom"),"1.25");
  await page.getByRole("button",{name:"Zoom out",exact:true}).click();
  assert.equal(await page.locator(".map-world").getAttribute("data-zoom"),"1.00");
  const canvas=page.locator(".map-canvas");
  const rect=await canvas.boundingBox();
  const before=await page.locator(".map-world").getAttribute("style");
  await page.mouse.move(rect.x+rect.width*.4,rect.y+rect.height*.48);
  await page.mouse.down(); await page.mouse.move(rect.x+rect.width*.4+70,rect.y+rect.height*.48+20,{steps:8});await page.mouse.up();
  assert.notEqual(await page.locator(".map-world").getAttribute("style"),before,"Map drag must pan the world");
  await page.getByRole("button",{name:"Recenter map",exact:true}).click();
  await page.locator(".world-pin").filter({hasText:"Eric"}).click();
  assert.match(await page.locator(".map-moment-card").innerText(),/At home/);
  await snap("map-selected");
  await page.locator(".map-card-main").click();
  const sheet=page.getByTestId("bottom-sheet");await sheet.waitFor();
  assert.match(await sheet.innerText(),/A little bowl of egg soup/);
  await page.getByRole("button",{name:"Looks good",exact:true}).click();
  await snap("post");
  await page.getByRole("button",{name:"Close",exact:true}).click();
  await page.reload({waitUntil:"networkidle"});
  await page.locator(".world-pin").filter({hasText:"Eric"}).click();
  await page.locator(".map-card-main").click();
  assert.equal(await page.getByRole("button",{name:"Looks good",exact:true}).getAttribute("aria-pressed"),"true","Reaction persists after refresh");
  await page.getByRole("button",{name:"Close",exact:true}).click();
  await page.getByRole("button",{name:"Yesterday",exact:true}).click();
  assert.equal(await page.locator(".world-pin").count(),2);
  await page.getByRole("button",{name:"Today",exact:true}).click();
  await page.getByRole("button",{name:"Feed",exact:true}).click();await snap("feed");
  await page.getByRole("navigation",{name:"Main navigation"}).getByRole("button",{name:"Chat",exact:true}).click();await snap("chat");
  await page.getByRole("navigation",{name:"Main navigation"}).getByRole("button",{name:"Memories",exact:true}).click();await snap("memories");
  await page.getByRole("button",{name:"Calendar",exact:true}).click();await snap("calendar");
  await page.getByRole("button",{name:"Recaps",exact:true}).click();await snap("recaps");
  const recapButton=await page.getByRole("button",{name:"Relive this month",exact:true}).boundingBox();
  const navBox=await page.getByRole("navigation",{name:"Main navigation"}).boundingBox();
  assert.ok(recapButton.y+recapButton.height<navBox.y,"Recap action must be visible above navigation without scrolling");
  await page.getByRole("navigation",{name:"Main navigation"}).getByRole("button",{name:"Profile",exact:true}).click();await snap("profile");
  await page.getByRole("button",{name:"Capture a meal",exact:true}).click();await snap("capture");
  await page.getByRole("button",{name:"Close",exact:true}).click();
  await page.getByRole("navigation",{name:"Main navigation"}).getByRole("button",{name:"Home",exact:true}).click();
  await page.setViewportSize({width:390,height:844});await snap("compact-home");
  assert.equal(await page.getByRole("button",{name:"Zoom in",exact:true}).isVisible(),true);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:["Map is default Home","Five food/avatar markers","Zoom in/out","Drag to pan","Recenter","Home post preview and detail","Persistent reaction","Yesterday filter","Feed","Chat","Memories grid/calendar/recap","Profile","Capture"],pageErrors:errors},null,2));
} finally {await browser.close();}
