// Bundles the TypeScript server into app/server.js (CommonJS) so the REDcowork
// Pod can run `node app/server.js` with production dependencies only.
import { build } from "esbuild";
await build({
  entryPoints: ["server/platform-entry.ts"],
  outfile: "app/server.js",
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node18",
  external: ["express", "../guard_sdk/*"],
  banner: { js: "// Generated by scripts/build-server.mjs from server/*.ts. Do not edit by hand." },
  logLevel: "info",
});
